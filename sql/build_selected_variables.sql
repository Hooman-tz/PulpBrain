	JOIN `fibersummary` ON `pulpeye`.`SampleID` = `fibersummary`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `fibersummary`.`Refining_Level`
	JOIN `fiberkinks` ON `pulpeye`.`SampleID` = `fiberkinks`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `fiberkinks`.`Refining_Level`
	JOIN `fwtdist` ON `pulpeye`.`SampleID` = `fwtdist`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `fwtdist`.`Refining_Level`
   	JOIN `fwtwidthdist` ON `pulpeye`.`SampleID` = `fwtwidthdist`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `fwtwidthdist`.`Refining_Level`
	JOIN `fiberdistributions` ON `pulpeye`.`SampleID` = `fiberdistributions`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `fiberdistributions`.`Refining_Level`
	LEFT JOIN `raman_coeffs` ON `pulpeye`.`SampleID` = `raman_coeffs`.`SampleID`
	JOIN `targets` ON `pulpeye`.`SampleID` = `targets`.`SampleID`
		AND `pulpeye`.`Refining_Level` = `targets`.`Refining_Level`;

    
